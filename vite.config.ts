import { resolve } from 'node:path'

import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { doors, originFor, serves } from 'kehikot-module-protocol/serve'
import { defineConfig, type Plugin } from 'vite'

import { BUILD, MANIFEST, TICKET, answer, servingAt, stream } from './doors.ts'
import { ID, PREFERRED_PORT } from './manifest.ts'
import { ours } from './skills.ts'

/**
 * The port this process really ended up on is not knowable here: `serves()` prefers `$PORT`, then
 * `PREFERRED_PORT`, and moves when that is taken. The skill names the origin it is on, so it is
 * corrected once the server is listening.
 */
function listening(): Plugin {
  return {
    name: 'factory-listening',
    configureServer(server) {
      server.httpServer?.once('listening', () => {
        const address = server.httpServer?.address()
        if (address && typeof address === 'object') servingAt(originFor(address.port))
      })
    },
  }
}

/**
 * - `serves()` first: it claims the port from PREFERRED_PORT (or $PORT from a host) and keeps the
 *   registration true. So no `server.port` here.
 * - `doors()` serves the manifest, the page at `/app` with the ticket and the build printed into
 *   it, `/healthz`, `/mcp`, `/api/*` (with `/api/watch` as a stream), and the skill's SKILL.md at
 *   `/kehikot/skills/factory.md`. A module is ONE ORIGIN.
 * - Loopback, and `cors: false` written rather than omitted: the page's ticket guards a merge.
 * - No `index.html` of its own: the page is generated by `doors()`, and `build.ts` writes one for
 *   the length of a build.
 */
export default defineConfig({
  base: './',
  plugins: [
    serves({ id: ID, prefer: PREFERRED_PORT }),
    listening(),
    doors({
      manifest: MANIFEST,
      answer,
      stream,
      build: BUILD,
      page: { title: 'Factory', ticket: TICKET },
      ours,
    }),
    react(),
    tailwindcss(),
  ],
  resolve: { alias: { '@': resolve(import.meta.dirname, 'src') } },
  server: { host: '127.0.0.1', cors: false },
})
